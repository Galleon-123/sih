/**
 * Robust fallback-aware translation resolver
 */
export const getTranslation = (langCode = 'en', key, fallback) => {
  if (!key) return fallback !== undefined ? fallback : '';
  const lang = (langCode || 'en').toLowerCase();
  const langObj = translations[lang] || translations.en;
  if (langObj && langObj[key] !== undefined && langObj[key] !== '') {
    return langObj[key];
  }
  if (translations.en && translations.en[key] !== undefined && translations.en[key] !== '') {
    return translations.en[key];
  }
  return fallback !== undefined ? fallback : '';
};

export default translations;
